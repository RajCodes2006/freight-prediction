from __future__ import annotations

from typing import Any, Dict


def _source_record(
    status: str,
    source_type: str,
    source: str,
    note: str,
    **extra: Any,
) -> Dict[str, Any]:
    record: Dict[str, Any] = {
        "status": status,
        "source_type": source_type,
        "source": source,
        "note": note,
    }
    record.update(extra)
    return record


def build_data_provenance(result: Dict[str, Any]) -> Dict[str, Any]:
    """Build an explicit provenance map for the numbers in a forecast response."""

    market_context = result.get("market_context") or {}
    benchmark_available = bool(market_context.get("available"))

    congestion = result.get("congestion") or {}
    loading = congestion.get("loading") or {}
    discharge = congestion.get("discharge") or {}

    forecast = result.get("forecast") or {}
    horizons = forecast.get("all_horizons") or {}
    forecast_live = forecast.get("current_level_source") == "LIVE_CALIBRATED"

    weather = result.get("weather") or {}
    weather_available = weather.get("status") == "AVAILABLE"

    vessel_decision = result.get("vessel_decision") or {}
    freight_rate_source = vessel_decision.get("freight_rate_source")

    if freight_rate_source == "LIVE_CALIBRATED_INDEX":
        freight_status = "MODELLED_ESTIMATE"
        freight_source = "Live-calibrated vessel-class index"
        freight_note = (
            "Estimated from the live-calibrated vessel-class index and the prototype "
            "baseline rate. It is not a route-specific charter quote."
        )
    else:
        freight_status = "ASSUMED"
        freight_source = "voyage_cost.py"
        freight_note = "Fallback prototype freight rate; not a live route-specific charter quote."

    return {
        "methodology": "Each value is labelled as LIVE, VERIFIED, HISTORICAL, CALCULATED, MODELLED, or ASSUMED. Assumptions are not presented as market quotes.",
        "market_benchmarks": _source_record(
            "LIVE" if benchmark_available else "UNAVAILABLE",
            "API",
            market_context.get("provider") or "OilPriceAPI",
            market_context.get("note") or "Live benchmark data unavailable; historical model data remains in use.",
            benchmarks=list((market_context.get("benchmarks") or {}).keys()),
        ),
        "forecast_level": _source_record(
            "LIVE_CALIBRATED" if forecast_live else "HISTORICAL",
            "CALIBRATED_MODEL" if forecast_live else "MODEL_DATASET",
            "Historical vessel-index relationships to live BDI/BCI" if forecast_live else "multihorizon_model_dataset.csv",
            "Current vessel-class level is calibrated from live benchmarks; forecast movement is still generated by the trained model." if forecast_live else "Current vessel-class level uses the historical model dataset; no live level calibration was applied.",
        ),
        "forecast_model": _source_record(
            "MODELLED",
            "ML_MODEL",
            "Saved forecast models + validation results",
            "Predictions and confidence come from the model registry and historical validation metrics.",
            horizons={
                str(h): {
                    "model_used": (v or {}).get("model_used"),
                    "confidence": (v or {}).get("confidence"),
                }
                for h, v in horizons.items()
                if isinstance(v, dict)
            },
        ),
        "freight_rate": _source_record(
            freight_status,
            "MARKET_CALIBRATED_ESTIMATE" if freight_status == "MODELLED_ESTIMATE" else "PROTOTYPE_ASSUMPTION",
            freight_source,
            freight_note,
        ),
        "bunker_cost": _source_record(
            "CALCULATED_FROM_ASSUMPTION" if weather_available else "ASSUMED",
            "WEATHER_ADJUSTED_ASSUMPTION" if weather_available else "PROTOTYPE_ASSUMPTION",
            "voyage_cost.py + Open-Meteo weather impact" if weather_available else "voyage_cost.py",
            "Base bunker cost is a prototype vessel-class assumption. When weather data is available, the cost is adjusted by the prototype weather-time multiplier; it is not a live bunker quote." if weather_available else "Prototype bunker cost by vessel class; not a live bunker quote.",
            multiplier=weather.get("bunker_cost_multiplier") if weather_available else 1.0,
        ),
        "weather": _source_record(
            "LIVE",
            "WEATHER_API",
            "Open-Meteo Marine + Weather API",
            "Route-sampled 7-day weather conditions are used by the prototype impact layer to adjust sailing time and bunker cost. This is operational decision support, not nautical navigation.",
            risk_level=weather.get("risk_level"),
            weather_risk_score=weather.get("weather_risk_score"),
            route_points=weather.get("route_points", []),
        ) if weather_available else _source_record(
            "UNAVAILABLE",
            "WEATHER_API",
            "Open-Meteo Marine + Weather API",
            "Weather data was unavailable for this request, so no weather adjustment was applied.",
        ),
        "port_charges": _source_record(
            "ASSUMED",
            "PROTOTYPE_ASSUMPTION",
            "voyage_cost.py",
            "Prototype port charges by vessel class; not a live tariff quote.",
        ),
        "sailing_time": _source_record(
            "CALCULATED",
            "ROUTE_ESTIMATE_PLUS_WEATHER" if weather_available else "ROUTE_ESTIMATE",
            "route_sailing.py + Open-Meteo weather impact" if weather_available else "route_sailing.py",
            "Calculated from port coordinates, route waypoints, planning speed, and a prototype weather adjustment for the first forecast window; not a live vessel schedule." if weather_available else "Calculated from port coordinates, route waypoints, and planning speed; not a live vessel schedule.",
            base_sailing_days=weather.get("base_sailing_days") if weather_available else None,
            weather_adjusted_sailing_days=weather.get("adjusted_sailing_days") if weather_available else None,
        ),
        "loading_congestion": _source_record(
            "VERIFIED" if loading.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "ASSUMED",
            "PORT_DATA" if loading.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "PROTOTYPE_FALLBACK",
            loading.get("source_name") or loading.get("source") or "No verified source",
            loading.get("metric_note") or loading.get("waiting_reason") or "No verified observation available.",
            observation_date=loading.get("observation_date"),
        ),
        "discharge_congestion": _source_record(
            "VERIFIED" if discharge.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "ASSUMED",
            "PORT_DATA" if discharge.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "PROTOTYPE_FALLBACK",
            discharge.get("source_name") or discharge.get("source") or "No verified source",
            discharge.get("metric_note") or discharge.get("waiting_reason") or "No verified observation available.",
            observation_date=discharge.get("observation_date"),
        ),
        "total_voyage_cost": _source_record(
            "CALCULATED",
            "OPTIMIZATION_ENGINE",
            "Decision engine",
            "Computed from cargo quantity, estimated/prototype freight rate, vessel time, prototype bunker cost, and prototype port charges.",
        ),
        "contract_economics": _source_record(
            "CALCULATED",
            "OPTIMIZATION_ENGINE",
            "Contract + risk model",
            "Derived from the estimated freight rate and modelled market movement.",
        ),
    }
