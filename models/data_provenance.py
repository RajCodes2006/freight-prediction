from __future__ import annotations

from typing import Any, Dict


def _source_record(
    status: str,
    source_type: str,
    source: str,
    note: str,
    **extra: Any,
) -> Dict[str, Any]:
    record: Dict[str, Any] = {
        "status": status,
        "source_type": source_type,
        "source": source,
        "note": note,
    }
    record.update(extra)
    return record


def build_data_provenance(result: Dict[str, Any]) -> Dict[str, Any]:
    """Build an explicit provenance map for the numbers in a forecast response."""

    market_context = result.get("market_context") or {}
    benchmark_available = bool(market_context.get("available"))

    congestion = result.get("congestion") or {}
    loading = congestion.get("loading") or {}
    discharge = congestion.get("discharge") or {}

    forecast = result.get("forecast") or {}
    horizons = forecast.get("all_horizons") or {}

    return {
        "methodology": "Each value is labelled as LIVE, VERIFIED, HISTORICAL, CALCULATED, MODELLED, or ASSUMED. Assumptions are not presented as market quotes.",
        "market_benchmarks": _source_record(
            "LIVE" if benchmark_available else "UNAVAILABLE",
            "API",
            market_context.get("provider") or "OilPriceAPI",
            market_context.get("note") or "Live benchmark data unavailable; historical model data remains in use.",
            benchmarks=list((market_context.get("benchmarks") or {}).keys()),
        ),
        "forecast_level": _source_record(
            "LIVE_CALIBRATED" if forecast.get("current_level_source") == "LIVE_CALIBRATED" else "HISTORICAL",
            "CALIBRATED_MODEL" if forecast.get("current_level_source") == "LIVE_CALIBRATED" else "MODEL_DATASET",
            "Historical SI/PI/CI relationship to live BDI/BCI" if forecast.get("current_level_source") == "LIVE_CALIBRATED" else "multihorizon_model_dataset.csv",
            "Current vessel-class level is calibrated from live benchmarks; forecast movement is still generated by the trained model.",
        ),
        "forecast_model": _source_record(
            "MODELLED",
            "ML_MODEL",
            "Saved forecast models + validation results",
            "Predictions and confidence come from the model registry and historical validation metrics.",
            horizons={
                str(h): {
                    "model_used": (v or {}).get("model_used"),
                    "confidence": (v or {}).get("confidence"),
                }
                for h, v in horizons.items()
                if isinstance(v, dict)
            },
        ),
        "freight_rate": _source_record(
            "ASSUMED",
            "PROTOTYPE_ASSUMPTION",
            "voyage_cost.py",
            "Prototype freight-rate values; not a live route-specific charter quote.",
        ),
        "bunker_cost": _source_record(
            "ASSUMED",
            "PROTOTYPE_ASSUMPTION",
            "voyage_cost.py",
            "Prototype bunker cost by vessel class; not a live bunker quote.",
        ),
        "port_charges": _source_record(
            "ASSUMED",
            "PROTOTYPE_ASSUMPTION",
            "voyage_cost.py",
            "Prototype port charges by vessel class; not a live tariff quote.",
        ),
        "sailing_time": _source_record(
            "CALCULATED",
            "ROUTE_ESTIMATE",
            "route_sailing.py",
            "Calculated from port coordinates, route waypoints, and planning speed; not a live vessel schedule.",
        ),
        "loading_congestion": _source_record(
            "VERIFIED" if loading.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "ASSUMED",
            "PORT_DATA" if loading.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "PROTOTYPE_FALLBACK",
            loading.get("source_name") or loading.get("source") or "No verified source",
            loading.get("metric_note") or loading.get("waiting_reason") or "No verified observation available.",
            observation_date=loading.get("observation_date"),
        ),
        "discharge_congestion": _source_record(
            "VERIFIED" if discharge.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "ASSUMED",
            "PORT_DATA" if discharge.get("data_status") == "VERIFIED_MEDIAN_WAITING" else "PROTOTYPE_FALLBACK",
            discharge.get("source_name") or discharge.get("source") or "No verified source",
            discharge.get("metric_note") or discharge.get("waiting_reason") or "No verified observation available.",
            observation_date=discharge.get("observation_date"),
        ),
        "total_voyage_cost": _source_record(
            "CALCULATED",
            "OPTIMIZATION_ENGINE",
            "Decision engine",
            "Computed from cargo quantity, prototype freight rate, vessel time, prototype bunker cost, and prototype port charges.",
        ),
        "contract_economics": _source_record(
            "CALCULATED",
            "OPTIMIZATION_ENGINE",
            "Contract + risk model",
            "Derived from prototype rate assumptions and the modelled market movement.",
        ),
    }
